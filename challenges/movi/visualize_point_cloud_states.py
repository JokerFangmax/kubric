def _load_json(path):
  with path.open("r", encoding="utf-8") as fp:
    return json.load(fp)


def _load_pickle(path):
  with path.open("rb") as fp:
    return pickle.load(fp)


def _require_file(path, message):
  if not path.exists():
    raise FileNotFoundError(message)


def _resolve_output_dir(args):
  if args.output_dir is not None:
    return args.output_dir
  return args.input_dir / "point_state_viz"


def _find_point_state_path(input_dir, metadata):
  point_state_summary = metadata.get("point_cloud_states", {})
  filename = point_state_summary.get("filename", POINT_STATE_FILENAME)
  point_state_path = input_dir / filename
  _require_file(
      point_state_path,
      f"Missing {point_state_path}. "
      "Run movi_ab_worker.py with point sampling enabled first.")
  return point_state_path


def _get_palette(num_instances):
  palette = []
  for index in range(num_instances):
    palette.append(ImageColor.getrgb(DEFAULT_COLORS[index % len(DEFAULT_COLORS)]))
  return palette


def _quaternions_to_rotation_matrices(quaternions):
  quaternions = np.asarray(quaternions, dtype=np.float32)
  quaternions = quaternions / np.clip(
      np.linalg.norm(quaternions, axis=-1, keepdims=True), a_min=1e-8, a_max=None)
  w = quaternions[:, 0]
  x = quaternions[:, 1]
  y = quaternions[:, 2]
  z = quaternions[:, 3]
  return np.stack([
      1. - 2. * (y * y + z * z),
      2. * (x * y - z * w),
      2. * (x * z + y * w),
      2. * (x * y + z * w),
      1. - 2. * (x * x + z * z),
      2. * (y * z - x * w),
      2. * (x * z - y * w),
      2. * (y * z + x * w),
      1. - 2. * (x * x + y * y),
  ], axis=-1).reshape((-1, 3, 3)).astype(np.float32)


def _camera_matrix_world(position, quaternion):
  matrix = np.eye(4, dtype=np.float32)
  matrix[:3, :3] = _quaternions_to_rotation_matrices(
      np.asarray(quaternion, dtype=np.float32)[None, :])[0]
  matrix[:3, 3] = np.asarray(position, dtype=np.float32)
  return matrix


def _project_points(points, camera_position, camera_quaternion, intrinsics):
  matrix_world = _camera_matrix_world(camera_position, camera_quaternion)
  homo_transform = np.linalg.inv(matrix_world)
  homo_intrinsics = np.zeros((3, 4), dtype=np.float32)
  homo_intrinsics[:, :3] = intrinsics
  point4d = np.concatenate(
      [np.asarray(points, dtype=np.float32), np.ones((len(points), 1), dtype=np.float32)],
      axis=1)
  projected = (homo_intrinsics @ homo_transform @ point4d.T).T
  image_coords = projected[:, :2] / projected[:, 2:3]
  depth_sign = np.sign(projected[:, 2])
  return image_coords, depth_sign


def _normalized_to_pixel(coords, image_size):
  width, height = image_size
  x = np.clip(np.floor(coords[:, 0] * width), 0, width - 1).astype(np.int32)
  y = np.clip(np.floor(coords[:, 1] * height), 0, height - 1).astype(np.int32)
  return np.stack([x, y], axis=-1)


def _load_rgba_image(input_dir, frame_id, resolution):
  rgba_path = input_dir / RGBA_TEMPLATE.format(frame_id)
  if rgba_path.exists():
    return Image.open(rgba_path).convert("RGBA")
  width = int(resolution[1])
  height = int(resolution[0])
  return Image.new("RGBA", (width, height), (255, 255, 255, 255))


def _load_segmentation_image(input_dir, frame_id):
  segmentation_path = input_dir / SEGMENTATION_TEMPLATE.format(frame_id)
  _require_file(segmentation_path, f"Missing {segmentation_path}.")
  return np.array(Image.open(segmentation_path), dtype=np.int32)


def _load_depth_image(input_dir, frame_id):
  depth_path = input_dir / DEPTH_TEMPLATE.format(frame_id)
  _require_file(depth_path, f"Missing {depth_path}.")
  return np.array(Image.open(depth_path), dtype=np.float32)


def _make_subset_indices(start, end, max_points):
  num_points = end - start
  if max_points <= 0 or num_points <= max_points:
    return np.arange(start, end, dtype=np.int32)
  relative = np.linspace(0, num_points - 1, num=max_points, dtype=np.int32)
  return start + relative


def _subset_existing_indices(indices, max_points):
  indices = np.asarray(indices, dtype=np.int32)
  if max_points <= 0 or len(indices) <= max_points:
    return indices
  relative = np.linspace(0, len(indices) - 1, num=max_points, dtype=np.int32)
  return indices[relative]


def _get_point_kinds(point_payload, expected_num_points):
  point_kinds = point_payload.get("point_kinds")
  if point_kinds is None:
    return np.full((expected_num_points,), POINT_KIND_VOLUME, dtype=np.uint8)
  point_kinds = np.asarray(point_kinds, dtype=np.uint8)
  if point_kinds.shape != (expected_num_points,):
    raise ValueError(
        f"Expected point_kinds with shape ({expected_num_points},), got {point_kinds.shape}.")
  return point_kinds


def _build_render_index_map(instances, max_points_per_object, point_kinds):
  render_indices = {}
  for instance in instances:
    start, end = [int(x) for x in instance["point_range"]]
    full_indices = np.arange(start, end, dtype=np.int32)
    if max_points_per_object <= 0 or full_indices.size <= max_points_per_object:
      render_indices[instance["instance_index"]] = full_indices
      continue

    instance_point_kinds = point_kinds[start:end]
    surface_indices = full_indices[instance_point_kinds == POINT_KIND_SURFACE]
    volume_indices = full_indices[instance_point_kinds == POINT_KIND_VOLUME]
    if surface_indices.size >= max_points_per_object:
      selected = _subset_existing_indices(surface_indices, max_points_per_object)
    else:
      remaining = max_points_per_object - surface_indices.size
      volume_selected = _subset_existing_indices(volume_indices, remaining)
      selected = np.concatenate([surface_indices, volume_selected], axis=0)
    render_indices[instance["instance_index"]] = selected.astype(np.int32)
  return render_indices


def _compute_world_bounds(point_states, axes):
  coords = point_states[:, :, axes].reshape(-1, 2)
  minimum = coords.min(axis=0)
  maximum = coords.max(axis=0)
  span = np.maximum(maximum - minimum, 1e-3)
  padding = 0.08 * span + 1e-3
  return minimum - padding, maximum + padding


def _world_to_canvas(points, minimum, maximum, image_size, margin):
  width, height = image_size
  points = np.asarray(points, dtype=np.float32)
  span = np.maximum(maximum - minimum, 1e-6)
  usable_width = max(width - 2 * margin, 1)
  usable_height = max(height - 2 * margin, 1)
  normalized = (points - minimum) / span
  x = margin + normalized[:, 0] * usable_width
  y = height - margin - normalized[:, 1] * usable_height
  return np.stack([x, y], axis=-1)


def _draw_arrow(draw, start, end, color, width=2):
  start = np.asarray(start, dtype=np.float32)
  end = np.asarray(end, dtype=np.float32)
  draw.line((float(start[0]), float(start[1]), float(end[0]), float(end[1])),
            fill=color, width=width)
  direction = end - start
  length = float(np.linalg.norm(direction))
  if length < 1e-6:
    return
  direction /= length
  normal = np.array([-direction[1], direction[0]], dtype=np.float32)
  arrow_head = 6.0
  left = end - arrow_head * direction + 0.5 * arrow_head * normal
  right = end - arrow_head * direction - 0.5 * arrow_head * normal
  draw.polygon(
      [(float(end[0]), float(end[1])),
       (float(left[0]), float(left[1])),
       (float(right[0]), float(right[1]))],
      fill=color)


def _volume_point_color(color):
  color = np.asarray(color, dtype=np.float32)
  shaded = 0.55 * color + 0.10 * 255.0
  return tuple(np.clip(np.round(shaded), 0, 255).astype(np.uint8).tolist())


def _surface_point_color(color):
  return tuple(np.asarray(color, dtype=np.uint8).tolist())


def _get_depth_tolerance(reference_depth, args):
  return args.depth_tolerance_abs + args.depth_tolerance_rel * max(float(reference_depth), 1.0)


def _point_matches_visibility(
    segmentation,
    depth_map,
    pixel_x,
    pixel_y,
    instance_label,
    point_depth,
    args,
):
  height, width = segmentation.shape
  radius = max(int(args.visibility_radius), 0)
  x0 = max(pixel_x - radius, 0)
  x1 = min(pixel_x + radius + 1, width)
  y0 = max(pixel_y - radius, 0)
  y1 = min(pixel_y + radius + 1, height)

  segmentation_patch = segmentation[y0:y1, x0:x1]
  object_mask = segmentation_patch == instance_label
  if not np.any(object_mask):
    return False

  patch_depth = depth_map[y0:y1, x0:x1]
  visible_surface_depth = float(np.min(patch_depth[object_mask]))
  tolerance = _get_depth_tolerance(visible_surface_depth, args)
  return abs(float(point_depth) - visible_surface_depth) <= tolerance


def _compute_instance_projection(
    object_points,
    camera_position,
    camera_quaternion,
    intrinsics,
    segmentation,
    depth_map,
    instance_label,
    image_size,
    args,
):
  if instance_label <= 0 or len(object_points) == 0:
    empty = np.zeros((0,), dtype=bool)
    return empty, np.zeros((0, 2), dtype=np.int32)

  image_coords, depth_sign = _project_points(
      object_points, camera_position, camera_quaternion, intrinsics)
  projected_pixels = _normalized_to_pixel(image_coords, image_size)
  point_depths = np.linalg.norm(
      object_points - np.asarray(camera_position, dtype=np.float32)[None, :], axis=1)

  valid = (
      (depth_sign > 0)
      & (image_coords[:, 0] >= 0.0)
      & (image_coords[:, 0] <= 1.0)
      & (image_coords[:, 1] >= 0.0)
      & (image_coords[:, 1] <= 1.0)
  )
  filtered = np.zeros(len(object_points), dtype=bool)

  for point_index in np.flatnonzero(valid):
    pixel_x, pixel_y = projected_pixels[point_index]
    if _point_matches_visibility(
        segmentation=segmentation,
        depth_map=depth_map,
        pixel_x=int(pixel_x),
        pixel_y=int(pixel_y),
        instance_label=int(instance_label),
        point_depth=float(point_depths[point_index]),
        args=args):
      filtered[point_index] = True

  return filtered, projected_pixels


def _compute_frame_projection_data(
    frame_points,
    frame_velocities,
    instances,
    render_index_map,
    point_kinds,
    metadata,
    frame_index,
    input_dir,
    frame_id,
    args,
):
  del frame_velocities  # only frame_points are required for visibility filtering
  segmentation = _load_segmentation_image(input_dir, int(frame_id))
  depth_map = _load_depth_image(input_dir, int(frame_id))
  camera = metadata["camera"]
  intrinsics = np.asarray(camera["K"], dtype=np.float32)
  camera_position = np.asarray(camera["positions"], dtype=np.float32)[frame_index]
  camera_quaternion = np.asarray(camera["quaternions"], dtype=np.float32)[frame_index]
  image_size = (segmentation.shape[1], segmentation.shape[0])

  projection_data = {}
  for instance in instances:
    instance_index = int(instance["instance_index"])
    point_indices = render_index_map[instance_index]
    object_points = frame_points[point_indices]
    instance_label = int(instance.get("visible_instance_index", -1)) + 1
    visible_mask, projected_pixels = _compute_instance_projection(
        object_points=object_points,
        camera_position=camera_position,
        camera_quaternion=camera_quaternion,
        intrinsics=intrinsics,
        segmentation=segmentation,
        depth_map=depth_map,
        instance_label=instance_label,
        image_size=image_size,
        args=args)
    projection_data[instance_index] = {
        "render_indices": point_indices,
        "point_kinds": point_kinds[point_indices],
        "visible_mask": visible_mask,
        "projected_pixels": projected_pixels,
        "instance_label": instance_label,
    }
  return projection_data


def _write_point_cloud_ply(path, vertices, colors):
  vertices = np.asarray(vertices, dtype=np.float32)
  colors = np.asarray(colors, dtype=np.uint8)
  with path.open("w", encoding="utf-8") as fp:
    fp.write("ply\n")
    fp.write("format ascii 1.0\n")
    fp.write(f"element vertex {len(vertices)}\n")
    fp.write("property float x\n")
    fp.write("property float y\n")
    fp.write("property float z\n")
    fp.write("property uchar red\n")
    fp.write("property uchar green\n")
    fp.write("property uchar blue\n")
    fp.write("end_header\n")
    for vertex, color in zip(vertices, colors):
      fp.write(
          f"{float(vertex[0]):.7f} {float(vertex[1]):.7f} {float(vertex[2]):.7f} "
          f"{int(color[0])} {int(color[1])} {int(color[2])}\n")


